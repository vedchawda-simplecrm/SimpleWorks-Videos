/**
 * Emits the browser build of the R-YaBot loader from the SAME pose maths the
 * Remotion composition uses, so the two can never drift apart.
 *
 *   node scripts/build-loader-css.mjs
 *
 * CSS keyframes rather than a requestAnimationFrame loop on purpose: this is
 * a loader shown while the app is busy, and compositor-driven animation keeps
 * moving when the main thread does not.
 *
 * Everything is emitted in units relative to --ryabot-size, never raw pixels.
 * The maths is written against a 512px box, but the component is used at 64
 * or 96px, and an absolute translateY or blur would be several times too
 * strong at those sizes.
 */
import fs from "node:fs";
import path from "node:path";
import {
  BREATH_PERIOD,
  FPS,
  HEAD,
  INTRO_FRAMES,
  LOADER_SIZE,
  PULSE_PERIOD,
  PULSE_R1,
  PULSE_RINGS,
  PULSE_STROKE,
  RING_BOX,
  idlePose,
  introPose,
  pulseFade,
  ringsAt,
} from "../src/videos/ryabot/loader/pose.ts";

const OUT = path.join(process.cwd(), "artifacts", "ryabot-loader");
fs.mkdirSync(OUT, { recursive: true });

const round = (n, d = 4) => Number(n.toFixed(d)).toString();
const pct = (n) => `${round(n, 3)}%`;
/** A length as a share of the box: translate percentages resolve against it. */
const rel = (px) => `${round((px / LOADER_SIZE) * 100, 4)}%`;
/** A length as an em, with font-size pinned to --ryabot-size on the root. */
const em = (px) => `${round(px / LOADER_SIZE, 5)}em`;

const transformOf = (p) =>
  `translateY(${rel(p.y)}) scale(${round(p.scaleX)}, ${round(p.scaleY)}) rotate(${round(p.rotate)}deg)`;

/**
 * Samples a pose function into keyframes at a fixed frame step.
 *
 * The final frame is always emitted, whether or not the step lands on it:
 * for the intro that last keyframe IS the idle's 0%, and dropping it would
 * leave the hand-off a hair short of rest.
 */
const keyframes = (name, frames, step, at, props) => {
  const sampled = [];
  for (let f = 0; f < frames; f += step) sampled.push(f);
  sampled.push(frames);
  const body = sampled
    .map((f) => `  ${pct((f / frames) * 100)} { ${props(at(f))} }`)
    .join("\n");
  return `@keyframes ${name} {\n${body}\n}`;
};

const motion = (p) => {
  const blur = p.blur > 0.02 ? ` filter: blur(${em(p.blur)});` : " filter: none;";
  return `transform: ${transformOf(p)};${blur}`;
};

const IDLE_S = BREATH_PERIOD / FPS;
const INTRO_S = INTRO_FRAMES / FPS;
const RING_S = PULSE_PERIOD / FPS;

/**
 * Ring k runs the same animation a third of a cycle ahead of ring k-1.
 *
 * In the intro the whole set is pushed back by (INTRO_S - RING_S) so that at
 * the end of the settle every ring is exactly where the idle's frame 0 wants
 * it - the same hand-off the body transform makes.
 */
const ringDelays = (offset) =>
  Array.from({ length: PULSE_RINGS }, (_, k) =>
    round(offset - (k / PULSE_RINGS) * RING_S, 5),
  );

const ringRules = (variant, delays) =>
  delays
    .map(
      (d, k) =>
        `.ryabot-loader--${variant} .ryabot-loader__ring:nth-child(${k + 1}) { animation-delay: ${d}s; }`,
    )
    .join("\n");

const css = `/* Generated by scripts/build-loader-css.mjs - do not edit by hand.
   Idle loop: ${BREATH_PERIOD} frames / ${IDLE_S}s, one breath.
   Intro:     ${INTRO_FRAMES} frames / ${INTRO_S}s, plays once.
   Pulses:    ${PULSE_RINGS} rings, ${RING_S}s each, a third of a cycle apart.
   The intro's last keyframe is the idle's 0% keyframe, which is what makes
   the hand-off between them invisible. All lengths are relative to
   --ryabot-size so the loader behaves identically at any size. */

.ryabot-loader {
  --ryabot-size: 128px;
  position: relative;
  width: var(--ryabot-size);
  height: var(--ryabot-size);
  /* Pins 1em to the box, so em lengths below scale with the loader. */
  font-size: var(--ryabot-size);
  /* No background: the art is a cut-out and the page shows through. */
}

.ryabot-loader__body {
  position: absolute;
  inset: 0;
  transform-origin: 50% 88%;
  will-change: transform;
}

.ryabot-loader__pose {
  position: absolute;
  inset: 0;
  width: 100%;
  height: 100%;
  object-fit: contain;
  user-select: none;
  -webkit-user-drag: none;
}

/* Pulses sit inside the transformed body, so they stay locked to the head as
   it floats, and before the images, so the head occludes them and each ring
   reads as coming out from behind it. */
.ryabot-loader__pulses {
  position: absolute;
  inset: 0;
}

.ryabot-loader__ring {
  position: absolute;
  left: ${rel(HEAD.cx - PULSE_R1)};
  top: ${rel(HEAD.cy - PULSE_R1)};
  width: ${rel(RING_BOX)};
  height: ${rel(RING_BOX)};
  border: ${em(PULSE_STROKE)} solid #F08A1E;
  border-radius: 50%;
  opacity: 0;
  animation: ryabot-ring ${RING_S}s linear infinite;
  will-change: transform, opacity;
}

/* Idle only: already seated, breathing forever. */
.ryabot-loader--idle .ryabot-loader__body {
  animation: ryabot-idle ${IDLE_S}s linear infinite;
}
.ryabot-loader--idle .ryabot-loader__pose--standing { opacity: 0; }
.ryabot-loader--idle .ryabot-loader__pose--meditating { opacity: 1; }
${ringRules("idle", ringDelays(0))}

/* With the one-shot settle first. The idle is listed second and starts at
   the delay, so it takes over the transform from the intro's fill. */
.ryabot-loader--intro .ryabot-loader__body {
  animation:
    ryabot-intro ${INTRO_S}s linear 1 forwards,
    ryabot-idle ${IDLE_S}s linear ${INTRO_S}s infinite;
}
.ryabot-loader--intro .ryabot-loader__pose--standing {
  animation: ryabot-out ${INTRO_S}s linear 1 forwards;
}
.ryabot-loader--intro .ryabot-loader__pose--meditating {
  opacity: 0;
  animation: ryabot-in ${INTRO_S}s linear 1 forwards;
}
/* No halo while it is still standing; it arrives with the settle. */
.ryabot-loader--intro .ryabot-loader__pulses {
  opacity: 0;
  animation: ryabot-pulses-in ${INTRO_S}s linear 1 forwards;
}
${ringRules("intro", ringDelays(INTRO_S - RING_S))}

/* A loader must not be the thing that makes someone ill. Frozen at the
   resting meditation pose, which is still a clear "working" signal. */
@media (prefers-reduced-motion: reduce) {
  .ryabot-loader .ryabot-loader__body { animation: none; transform: none; }
  .ryabot-loader .ryabot-loader__pose--standing { animation: none; opacity: 0; }
  .ryabot-loader .ryabot-loader__pose--meditating { animation: none; opacity: 1; }
  .ryabot-loader .ryabot-loader__pulses { animation: none; opacity: 0; }
  .ryabot-loader .ryabot-loader__ring { animation: none; opacity: 0; }
}

${keyframes("ryabot-idle", BREATH_PERIOD, 5, idlePose, motion)}

${keyframes("ryabot-intro", INTRO_FRAMES, 2, introPose, motion)}

${keyframes("ryabot-out", INTRO_FRAMES, 2, introPose, (p) => `opacity: ${round(1 - p.blend)};`)}

${keyframes("ryabot-in", INTRO_FRAMES, 2, introPose, (p) => `opacity: ${round(p.blend)};`)}

${keyframes("ryabot-pulses-in", INTRO_FRAMES, 3, pulseFade, (v) => `opacity: ${round(v)};`)}

${keyframes(
  "ryabot-ring",
  PULSE_PERIOD,
  3,
  (f) => ringsAt(f)[0],
  (r) => `transform: scale(${round(r.scale)}); opacity: ${round(r.opacity)};`,
)}
`;

fs.writeFileSync(path.join(OUT, "ryabot-loader.css"), css);
console.log(
  `ryabot-loader.css  ${(css.length / 1024).toFixed(1)}KB  idle ${IDLE_S}s  intro ${INTRO_S}s  ${PULSE_RINGS} rings @ ${RING_S}s`,
);
